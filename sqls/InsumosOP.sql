SELECT PR_ORDEMSEPARACAO.CDORDEMSEPARACAO,
       PR_ORDEMSEPARACAO.SEQ_COUNT,          
       PR_MATERIALOP.STATUS,      
       BA_PRODUTO.CDPRODUTO,
       BA_PRODUTO.DSPRODUTO,   
       PR_MATERIALOP.FKORDEMSEPARACAO,
       PR_MATERIALOP.QUANTIDADE_SOLICITADA,
       PR_MATERIALOP.QUANTIDADE_PREVISTA,
       PR_MATERIALOP.QUANTIDADE_ENTREGUE,
       COALESCE(PR_MATERIALOP.QUANTIDADE_DEVOLVIDA, 0) AS QUANTIDADE_DEVOLVIDA,
       PR_ORDEMSEPARACAO.DTGERACAO,
      (SELECT BA_USUARIO.DSUSUARIO
         FROM BA_USUARIO
        WHERE BA_USUARIO.PKUSUARIO = PR_ORDEMSEPARACAO.FKUSUARIO_GERACAO) AS DSUSUARIO_GERACAO,
      (SELECT BA_USUARIO.DSUSUARIO
         FROM BA_USUARIO
        WHERE BA_USUARIO.PKUSUARIO = PR_MATERIALOP.FKUSUARIO_CONF) AS DSUSUARIO_CONFERENCIA, 
       PR_MATERIALOP.OBS_CONF AS OBS_CONFERENCIA
  FROM PR_MATERIALOP,
       BA_PRODUTO,
       BA_PARAMPR,
       PR_ORDEMSEPARACAO
 WHERE PR_MATERIALOP.FKPRODUTO        = BA_PRODUTO.PKPRODUTO
   AND PR_MATERIALOP.FKORDEMPRODUCAO  = :FKORDEMPRODUCAO
   AND PR_MATERIALOP.FKORDEMSEPARACAO = PR_ORDEMSEPARACAO.PKORDEMSEPARACAO
   AND BA_PARAMPR.CDEMPRESA           = PR_ORDEMSEPARACAO.CDEMPRESA