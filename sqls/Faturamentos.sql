    SELECT DISTINCT
           FA_NOTA.CDNOTA             AS FATURAMENTO,
           IIF(COALESCE(FA_ITNOTA.FKCONSULTOR, 0) = 0,
               COALESCE(FA_NOTA.FKCONSULTOR, 0),
               FA_ITNOTA.FKCONSULTOR) AS FKCONSULTOR,
           IIF(COALESCE(FA_ITNOTA.FKVENDEDOR, 0) = 0,
               COALESCE(FA_NOTA.FKVENDEDOR, 0),
               FA_ITNOTA.FKVENDEDOR)  AS FKVENDEDOR,
           FA_NOTA.PKNOTA             AS PKNOTADOCTO,
           FA_ITNOTA.PKITNOTA         AS PKITEM,
           100                        AS P_SOLICITACAO,  -- Nota
           BA_PESSOA.CDPESSOA || ' - ' ||
           BA_PESSOA.DSPESSOA         AS CLIENTE,
           BA_PRODUTO.PKPRODUTO,
           BA_PRODUTO.CDPRODUTO,
           BA_PRODUTO.DSPRODUTO,
           FA_NOTA.DTEMISSAO,
           BA_NATUREZAOPERACAO.CFOP,
           FA_ITNOTA.QUANTIDADE,
           FA_ITNOTA.PRECOLIQUIDO_UNIT,
           FA_ITNOTA.VL_TOTALITEM,
           FA_ITNOTA.VL_ICMS,
           FA_ITNOTA.VL_ICMS_SUBST,
           FA_ITNOTA.VL_PIS +
           FA_ITNOTA.VL_COFINS        AS VL_PISCOFINS,
           FA_ITNOTA.VL_ISS,
           FA_ITNOTA.VL_IPI           AS VL_IPI,
           FA_NOTA.VL_IPI             AS TOTAL_IPI_NOTA,
           FA_ITNOTA.VL_TOTALITEM -
           FA_ITNOTA.VL_ICMS -
           FA_ITNOTA.VL_PIS -
           FA_ITNOTA.VL_ISS -
           FA_ITNOTA.VL_COFINS        AS FATURAMENTO_LIQUIDO
      FROM FA_NOTA,
           FA_ITNOTA,
           BA_PESSOA,
           BA_PRODUTO,
           BA_NATUREZAOPERACAO
     WHERE FA_NOTA.DTEMISSAO                  BETWEEN :DT1 AND :DT2
       AND FA_NOTA.PKNOTA                     = FA_ITNOTA.FKNOTA
       AND FA_NOTA.FKPESSOA                   = BA_PESSOA.PKPESSOA
       AND FA_NOTA.STATUS                     <> 'C'
       AND FA_NOTA.DEVOLVIDA                  = 1
       AND FA_ITNOTA.FKPRODUTO                = BA_PRODUTO.PKPRODUTO
       AND FA_ITNOTA.FKNATUREZAOPERACAO       = BA_NATUREZAOPERACAO.PKNATUREZAOPERACAO
       AND BA_NATUREZAOPERACAO.FKNATUREZATIPO = 11

    UNION ALL

    SELECT DISTINCT
           FA_DOCTO.CDDOCTO            AS FATURAMENTO,
           IIF(COALESCE(FA_ITDOCTO.FKCONSULTOR, 0) = 0,
               COALESCE(FA_DOCTO.FKCONSULTOR, 0),
               FA_ITDOCTO.FKCONSULTOR) AS FKCONSULTOR,
           IIF(COALESCE(FA_ITDOCTO.FKVENDEDOR, 0) = 0,
               COALESCE(FA_DOCTO.FKVENDEDOR, 0),
               FA_ITDOCTO.FKVENDEDOR)  AS FKVENDEDOR,
           FA_DOCTO.PKDOCTO            AS PKNOTADOCTO,
           FA_ITDOCTO.PKITDOCTO        AS PKITEM,
           0                           AS P_SOLICITACAO,  -- Documento
           BA_PESSOA.CDPESSOA || ' - ' ||
           BA_PESSOA.DSPESSOA          AS CLIENTE,
           BA_PRODUTO.PKPRODUTO,
           BA_PRODUTO.CDPRODUTO,
           BA_PRODUTO.DSPRODUTO,
           FA_DOCTO.DTEMISSAO,
           CAST(' ' AS VARCHAR(10))    AS CFOP,
           FA_ITDOCTO.QUANTIDADE,
           FA_ITDOCTO.PRECOLIQUIDO_UNIT,
           FA_ITDOCTO.VL_TOTALITEM,
           CAST(0 AS NUMERIC(15,4))    AS VL_ICMS,
           CAST(0 AS NUMERIC(15,4))    AS VL_ICMS_SUBST,
           CAST(0 AS NUMERIC(15,4))    AS VL_PISCOFINS,
           CAST(0 AS NUMERIC(15,4))    AS VL_ISS,
           CAST(0 AS NUMERIC(15,4))    AS VL_IPI,
           CAST(0 AS NUMERIC(15,4))    AS TOTAL_IPI_NOTA,
           FA_ITDOCTO.VL_TOTALITEM     AS FATURAMENTO_LIQUIDO
     FROM FA_DOCTO,
          FA_ITDOCTO,
          BA_PESSOA,
          BA_PRODUTO
    WHERE FA_DOCTO.DTEMISSAO   BETWEEN :DT1 AND :DT2
      AND FA_DOCTO.PKDOCTO     = FA_ITDOCTO.FKDOCTO
      AND FA_DOCTO.FKPESSOA    = BA_PESSOA.PKPESSOA
      AND FA_ITDOCTO.FKPRODUTO = BA_PRODUTO.PKPRODUTO
      AND FA_DOCTO.STATUS      <> 'C'