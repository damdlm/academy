
SELECT CAST(
       BA_OPERACAOENGENHARIA.CDOPERACAOENGENHARIA || ' - ' ||
       BA_OPERACAOENGENHARIA.DSOPERACAOENGENHARIA
       AS "DMDESC(80)") AS CDDSOPERACAOENGENHARIA,
       PR_PROCESSOOP.SEQUENCIA,
       PR_PROCESSOOP.QT_ORIGINAL,
       PR_PROCESSOOP.QT_LIBERADA, 
       PR_PROCESSOOP.QT_PRODUZIDA,
       CAST(
       BA_EQUIPAMENTO.CDEQUIPAMENTO || ' - ' ||
       BA_EQUIPAMENTO.DSEQUIPAMENTO AS "DMDESC(80)") AS EQUIPAMENTO,
       PR_PROCESSOOP.OBSERVACAO,
       PR_PROCESSOOP.STATUS
  FROM PR_PROCESSOOP,
       BA_OPERACAOENGENHARIA,
       PR_STATUSPRODUCAO,
       BA_EQUIPAMENTO
 WHERE BA_OPERACAOENGENHARIA.PKOPERACAOENGENHARIA = PR_PROCESSOOP.FKOPERACAO
   AND PR_PROCESSOOP.FKORDEMPRODUCAO              = :PKORDEMPRODUCAO
   AND PR_PROCESSOOP.STATUS                       <> 'C'
   AND PR_STATUSPRODUCAO.PKSTATUSPRODUCAO         = PR_PROCESSOOP.FKSTATUSPRODUCAO
   AND BA_EQUIPAMENTO.PKEQUIPAMENTO               = PR_PROCESSOOP.FKEQUIPAMENTO
 ORDER BY PR_PROCESSOOP.SEQUENCIA