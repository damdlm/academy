SELECT DISTINCT
       VE_ORCAMENTO.CDORCAMENTO AS NR_ORCAMENTO,
       VE_ORCAMENTO.FKPESSOA AS CDPESSOA,                
       VE_ORCAMENTO.DTEMISSAO AS DT_EMISSAO,             
       VE_ORCAMENTO.HORAEMISSAO,
       VE_ORCAMENTO.VL_TOTALLIQUIDO AS VL_LIQUIDO,
       VE_ORCAMENTO.OBS  AS OBS_ORCAMENTO,
       VE_ORCAMENTO.CONTATO,
       VE_ORCAMENTO.TITULO,                              
       VE_ORCAMENTO.VL_TOTALLIQUIDO,
       VE_ORCAMENTO.VL_TOTAL_IPI,
       BA_UNMEDIDA.CDUNMEDIDA AS UNMEDIDA,
       BA_COLABORADOR.CDCOLABORADOR AS CDCONSULTOR,
       BA_COLABORADOR.DSCOLABORADOR AS DSCONSULTOR,
       BA_VENDEDOR.CDVENDEDOR,
       BA_VENDEDOR.DSVENDEDOR,
       VE_ITORCAMENTO.PKITORCAMENTO,
       VE_ITORCAMENTO.PRAZO_ENTREGA,
       VE_ITORCAMENTO.PRECOLIQUIDO_UNIT *
       VE_ITORCAMENTO.QUANTIDADE AS VL_LIQUIDO,
       VE_ITORCAMENTO.VL_IPI,
       VE_ITORCAMENTO.VL_ICMS,
       VE_ITORCAMENTO.DTENTREGA,
       VE_ITORCAMENTO.QUANTIDADE,
       BA_PRODUTO.CDPRODUTO,                                                         
       BA_PRODUTO.CDFABRICANTE,
       CAST(VE_ITORCAMENTO.DSPRODUTO||' - '||
       COALESCE(VE_ITORCAMENTO.OBS_ITEM,'')
       AS "DMOBS(5000)") AS DSPRODUTO
  FROM VE_ORCAMENTO,
       VE_ITORCAMENTO,
       BA_PRODUTO,
       BA_PESSOA,
       BA_VENDEDOR,
       BA_COLABORADOR,
       BA_UNMEDIDA
 WHERE VE_ORCAMENTO.PKORCAMENTO     = VE_ITORCAMENTO.FKORCAMENTO
   AND VE_ORCAMENTO.PKORCAMENTO     = :PKORIGEM
   AND BA_PRODUTO.PKPRODUTO         = VE_ITORCAMENTO.FKPRODUTO
   AND BA_UNMEDIDA.PKUNMEDIDA       = VE_ITORCAMENTO.FKUNMEDIDA
   AND VE_ITORCAMENTO.STATUS        <> 'C'
   AND BA_PESSOA.PKPESSOA           = VE_ORCAMENTO.FKPESSOA
   AND BA_VENDEDOR.PKVENDEDOR       = VE_ORCAMENTO.FKVENDEDOR
   AND BA_COLABORADOR.PKCOLABORADOR = VE_ORCAMENTO.FKCONSULTOR
