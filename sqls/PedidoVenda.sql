 SELECT VE_PEDIDO.PKPEDIDO,
        VE_PEDIDO.FKORIGEM,
        VE_PEDIDO.PKORIGEM,
        VE_PEDIDO.CDPEDIDO       AS PEDIDO,
        VE_PEDIDO.DTPEDIDO,
        BA_PESSOA.CDPESSOA || ' - ' ||
        BA_PESSOA.DSPESSOA       AS CLIENTE,
        VE_TPPEDIDO.DSTPPEDIDO   AS TP_PEDIDO,
        BA_CONDPAGTO.DSCONDPAGTO AS COND_PAGTO,
        BA_PRODUTO.CDPRODUTO     AS COD_PRODUTO,
        BA_PRODUTO.DSPRODUTO     AS PRODUTO,
        VE_ITPEDIDO.QUANTIDADE,
        VE_ITPEDIDO.PRECOLIQUIDO_UNIT,
        VE_ITPEDIDO.PRECOBRUTO_UNIT, 
        VE_ITPEDIDO.VL_TOTALITEM,
        FA_PEDIDONOTA.FKITNOTADOCTO AS PKITEM,
        FA_PEDIDONOTA.P_SOLICITACAO 
   FROM VE_PEDIDO,
        BA_PESSOA,
        VE_TPPEDIDO,
        VE_ITPEDIDO,
        BA_PRODUTO,
        FA_PEDIDONOTA,
        BA_CONDPAGTO,
        FI_TPCOBRANCA
  WHERE FA_PEDIDONOTA.FKITPEDIDO    = VE_ITPEDIDO.PKITPEDIDO
    AND VE_PEDIDO.FKPESSOA          = BA_PESSOA.PKPESSOA
    AND VE_ITPEDIDO.FKPEDIDO        = VE_PEDIDO.PKPEDIDO
    AND VE_PEDIDO.STATUS            <> 'C'
    AND VE_ITPEDIDO.STATUS          <> 'C'
    AND VE_ITPEDIDO.FKPRODUTO       = BA_PRODUTO.PKPRODUTO
    AND VE_PEDIDO.FKTPPEDIDO        = VE_TPPEDIDO.PKTPPEDIDO
    AND VE_PEDIDO.FKCONDPAGTO       = BA_CONDPAGTO.PKCONDPAGTO
    AND FA_PEDIDONOTA.FKITNOTADOCTO = :PKITEM
    AND FA_PEDIDONOTA.P_SOLICITACAO = :P_SOLICITACAO