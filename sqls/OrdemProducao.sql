 SELECT PR_ORDEMPRODUCAO.PKORDEMPRODUCAO,
        PR_ORDEMPRODUCAO.CDORDEMPRODUCAO,
        PR_ORDEMPRODUCAO.DSORDEMPRODUCAO,
        PR_ORDEMPRODUCAO.STATUS,
        PR_ORDEMPRODUCAO.DTGERACAO,
        PR_ORDEMPRODUCAO.QUANTIDADE_PRODUCAO
   FROM PR_ORDEMPRODUCAO, FA_PEDIDONOTA
  WHERE PR_ORDEMPRODUCAO.FKITPEDIDO = FA_PEDIDONOTA.FKITPEDIDO
    AND PR_ORDEMPRODUCAO.STATUS     <> 'C'
    AND FA_PEDIDONOTA.FKITNOTADOCTO = :PKITEM
    AND FA_PEDIDONOTA.P_SOLICITACAO = :P_SOLICITACAO