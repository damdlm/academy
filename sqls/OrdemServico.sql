SELECT VE_ORDEMSERVICO.PKORDEMSERVICO,
       VE_ORDEMSERVICO.CDORDEMSERVICO, 
       SERVICO.CDPRODUTO,
       VE_ITORDEMSERVICO.DSPRODUTO,
       VE_ORDEMSERVICO.VL_SERVICOS,
       VE_ORDEMSERVICO.VL_TOTAL_BRUTO,
       VE_ORDEMSERVICO.VL_TOTAL_LIQUIDO,
       VE_ITORDEMSERVICO.PRECOBRUTO_UNIT,
       VE_ITORDEMSERVICO.PRECOLIQUIDO_UNIT,
       VE_ITORDEMSERVICO.QUANTIDADE,
       VE_ITORDEMSERVICO.VL_TOTALITEM,
       VE_ORDEMSERVICO.DTEMISSAO,
       VE_ORDEMSERVICO.DTPREVISAO
  FROM VE_ORDEMSERVICO,
       FA_ORDEMSERVICONOTA,
       BA_PRODUTO SERVICO,
       VE_ITORDEMSERVICO
 WHERE VE_ORDEMSERVICO.PKORDEMSERVICO    = FA_ORDEMSERVICONOTA.FKORDEMSERVICO
   AND VE_ORDEMSERVICO.STATUS            <> 'C'
   AND SERVICO.PKPRODUTO                 = VE_ITORDEMSERVICO.FKPRODUTO
   AND VE_ORDEMSERVICO.PKORDEMSERVICO    = VE_ITORDEMSERVICO.FKORDEMSERVICO
   AND VE_ITORDEMSERVICO.TPPRODUTO       = 1
   AND FA_ORDEMSERVICONOTA.FKNOTADOCTO   = :PKNOTADOCTO
   AND FA_ORDEMSERVICONOTA.P_SOLICITACAO = :P_SOLICITACAO